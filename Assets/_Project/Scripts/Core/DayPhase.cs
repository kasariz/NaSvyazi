namespace NaSvyazi.Core
{
    /// <summary>Фазы рабочего дня.</summary>
    public enum DayPhase
    {
        Preparing, // утро: салон закрыт, время стоит — можно заказать и разложить товар
        Open,      // салон открыт, идёт время, приходят покупатели
        Closing,   // время вышло: новые покупатели не приходят, обслуживаем оставшихся
        Summary    // показан отчёт за день
    }
}
